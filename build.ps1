        -RedirectStandardOutput $gpblog
    if ($gpbproc.ExitCode -ne 0) { throw 'game move-blocked test failed' }
    $gpbline = Get-Content $gpblog -Raw
    foreach ($need in @('selector=1', 'explored=0', 'game_cursor=256 id=65')) {
        if ($gpbline -notmatch [regex]::Escape($need)) {
            throw "game move blocked-icon regression ($need): $gpbline"
        }
