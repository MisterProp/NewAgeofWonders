    $sbench = Join-Path $Here 'tools\shadow_bench.py'
    if ((Get-Command python -ErrorAction SilentlyContinue) -and (Test-Path $sbench)) {
        & python $sbench $mroot
        if ($LASTEXITCODE -ne 0) { throw "shadow benchmark regressed ($LASTEXITCODE)" }
    }
    Write-Host 'building animation smoke test: ok'
    # The move-selection pointer and the hexagon marker (docs/09_GAME_SCREEN.md
    # 6.9). With one of your armies selected the pointer becomes the walk / sail /
    # fly icon - the art of the army's move types, `Cursors.ilb` 0x40 / 0x42 / 0x44
    # (`AoWE.TSelectedArmy.UpdateMoveCursor` 0x55793440, state 0x100) - or its
    # "blocked" twin (0x41/0x43/0x45, the engine's `| 1`) on a hex the seated
    # player has not explored: that routine ORs bit 0 unless its move-point table
    # holds a zero, and `TArmy.CreateMovePointTable` fills 1 / 0xFF, so what is
    # left of the test is the exploration gate. The blue `General.ILB` `3dHex`
    # marker (ids 6/7) rings the hovered hex meanwhile
    # (`ShowFront/BackHexagonSelector`, shown by `TMoveSelector.Activate`).
    # On Tutorial.hsm the hero army at (15,34) is selected with the same two
    # clicks the select test uses; the hex next to it is inside the scenario-start
    # vision (`TArmy.UpdateExploration`, radius 4) and a hex well outside it is
    # not, so both icons are exercised.
    $gppng = Join-Path $BinDir 'game_movecursor.png'
    $gplog = Join-Path $BinDir 'game_movecursor.txt'
    Remove-Item $gppng, $gplog -Force -ErrorAction SilentlyContinue
    $gpargs = ('--root "{0}" --screen game --no-music --no-cursor --render "{1}" ' +
               '--game-click 513 141 --game-click 220 216 --mouse 236 200') -f $mroot, $gppng
    $gpproc = Start-Process -FilePath (Join-Path $BinDir 'AoW.exe') `
        -ArgumentList $gpargs -Wait -PassThru -NoNewWindow `
        -RedirectStandardOutput $gplog
    if ($gpproc.ExitCode -ne 0) { throw 'game move-cursor test failed' }
    $gpline = Get-Content $gplog -Raw
    foreach ($need in @('game_army=15,34', 'selector=1', 'explored=1',
                        'game_cursor=256 id=64')) {
        if ($gpline -notmatch [regex]::Escape($need)) {
            throw "game move cursor regression ($need): $gpline"
        }
    }
    # The marker's far wall must have the hovered hex's own art composited back
    # over it (the army standing there), not just the plain blue fill.
    if ($gpline -notmatch 'selector=1 sel_px=([1-9]\d*)') {
        throw "game move marker occlusion regression: $gpline"
    }
    Remove-Item $gppng, $gplog -Force
    $gpbpng = Join-Path $BinDir 'game_moveblocked.png'
    $gpblog = Join-Path $BinDir 'game_moveblocked.txt'
    Remove-Item $gpbpng, $gpblog -Force -ErrorAction SilentlyContinue
    $gpbargs = ('--root "{0}" --screen game --no-music --no-cursor --render "{1}" ' +
                '--game-click 513 141 --game-click 220 216 --mouse 400 380') -f $mroot, $gpbpng
    $gpbproc = Start-Process -FilePath (Join-Path $BinDir 'AoW.exe') `
