    # The per-building transparency check: one checkerboard sheet of every
    # structure sprite (tools/buildings_sheet.py). A sprite that still carries its
    # background would be obvious there; mapres_test's audit gates it too.
    $bsheet = Join-Path $BinDir 'buildings_sheet.png'
    Remove-Item $bsheet -Force -ErrorAction SilentlyContinue
    $bspath = Join-Path $Here 'tools\buildings_sheet.py'
