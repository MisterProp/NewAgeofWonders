    $gpcpng = Join-Path $BinDir 'game_markercity.png'
    $gpclog = Join-Path $BinDir 'game_markercity.txt'
    Remove-Item $gpcpng, $gpclog -Force -ErrorAction SilentlyContinue
    $gpcargs = ('--root "{0}" --screen game --no-music --no-cursor --render "{1}" ' +
                '--game-click 513 141 --game-click 220 216 --game-click 514 112 ' +
