function Find-Compiler {
    foreach ($c in 'g++', 'clang++', 'g++.exe', 'clang++.exe') {
        $cmd = Get-Command $c -ErrorAction SilentlyContinue
        if ($cmd) { return $cmd.Source }
    }
    foreach ($p in 'C:\msys64\ucrt64\bin\g++.exe', 'C:\msys64\mingw64\bin\g++.exe') {
        if (Test-Path $p) { return $p }
    }
    if (Get-Command cl -ErrorAction SilentlyContinue) { return 'cl' }
    throw 'No C++ compiler found on PATH (need g++, clang++ or cl).'
}

