    Remove-Item $gpbpng, $gpblog -Force
    # ...and a hex that carries a *city*: its art must show inside the marker too
    # (the case the marker's two halves exist for - the engine sandwiches the hex's
    # contents between them; the city here is the halfling home city on Tutorial.hsm
