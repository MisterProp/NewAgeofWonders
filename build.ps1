    # Performance guard for the interactive feel. A hover step must not rebuild the
    # game-root ILB index or re-decode `Cursors.ilb`, and a move's level re-render
    # must reuse the decoded libraries - the shared caches in mapviz.cpp are what
    # make that so. Measured: hover 0.3 ms, move render 28 ms (both were ~340 ms /
    # ~286 ms before the caches). The thresholds are ~15 x the measured values, so
    # they only trip when that caching is lost, not on a slow machine.
    $gbpng = Join-Path $BinDir 'game_bench.png'
    $gblog = Join-Path $BinDir 'game_bench.txt'
