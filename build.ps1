        '27 28' = 'race=[Elf] race_id=4'       # Heartwood, the elven capital
        '17 23' = 'race=[Goblin] race_id=10'   # Claywood
        '73 25' = 'race=[Orc] race_id=9'       # Ambrudor
        '20 16' = 'race=[Dwarf] race_id=6'     # Vinisheer
    }
    foreach ($tile in $heartwood.Keys) {
        Remove-Item $stracepng, $stracelog, $straceerr -Force -ErrorAction SilentlyContinue
        $straceargs = ('--root "{0}" --start-map "Heartwood Forest.HSM" ' +
                       '--structure-panel --structure-tile {1} --render "{2}" ' +
                       '--no-music --no-cursor') -f $mroot, $tile, $stracepng
        $straceproc = Start-Process -FilePath (Join-Path $BinDir 'AoW.exe') `
            -ArgumentList $straceargs -Wait -PassThru -NoNewWindow `
            -RedirectStandardOutput $stracelog -RedirectStandardError $straceerr
        $straceline = (Get-Content $stracelog -Raw) + (Get-Content $straceerr -Raw)
        if ($straceline -notmatch [regex]::Escape($heartwood[$tile])) {
            throw "structure race label regression at tile ${tile}: $straceline"
        }
    }
    Remove-Item $stracepng, $stracelog, $straceerr -Force
    Write-Host 'structure race label smoke test: ok'
    # A large building is selectable on every tile its sprite covers, not only
    # on its centre (docs/25_STRUCTURE_PANEL.md section 5). Barondir Bay's size-4
    # capital is the single City.TCity at (12,20); its resource's TTerrainList
    # entries 0/1/2/6 cover (12,20), (12,19), (13,19) and (11,19). Every covered
    # tile must open the same city (game_struct_hx/hy stays its home hex), while
    # a tile outside the footprint (14,20) must not.
    $sttilepng = Join-Path $BinDir 'structure_tile.png'
    $sttilelog = Join-Path $BinDir 'structure_tile.txt'
    $sttileerr = Join-Path $BinDir 'structure_tile.err'
    foreach ($tile in @('12 19', '13 19', '11 19')) {
        Remove-Item $sttilepng, $sttilelog, $sttileerr -Force -ErrorAction SilentlyContinue
        $sttileargs = ('--root "{0}" --start-map "Barondir Bay.HSM" ' +
                       '--scen-human 0 --structure-panel --structure-tile {1} ' +
                       '--render "{2}" --no-music --no-cursor') -f $mroot, $tile, $sttilepng
        $sttileproc = Start-Process -FilePath (Join-Path $BinDir 'AoW.exe') `
            -ArgumentList $sttileargs -Wait -PassThru -NoNewWindow `
            -RedirectStandardOutput $sttilelog -RedirectStandardError $sttileerr
        $sttileline = (Get-Content $sttilelog -Raw) + (Get-Content $sttileerr -Raw)
        if ($sttileline -notmatch [regex]::Escape("structure_tile=$($tile -replace ' ', ',')")) {
            throw "structure footprint regression at tile ${tile}: $sttileline"
        }
        if ($sttileline -notmatch [regex]::Escape('structure_panel=12,20 city=1')) {
            throw "structure footprint opened the wrong object at tile ${tile}: $sttileline"
        }
    }
    Remove-Item $sttilepng, $sttilelog, $sttileerr -Force -ErrorAction SilentlyContinue
    $stoutargs = ('--root "{0}" --start-map "Barondir Bay.HSM" --scen-human 0 ' +
                  '--structure-panel --structure-tile 14 20 --render "{1}" ' +
                  '--no-music --no-cursor') -f $mroot, $sttilepng
    $stoutproc = Start-Process -FilePath (Join-Path $BinDir 'AoW.exe') `
        -ArgumentList $stoutargs -Wait -PassThru -NoNewWindow `
        -RedirectStandardOutput $sttilelog -RedirectStandardError $sttileerr
    $stoutline = (Get-Content $sttilelog -Raw) + (Get-Content $sttileerr -Raw)
    if ($stoutline -notmatch 'no structure to open') {
        throw "structure footprint selected the empty tile (14,20): $stoutline"
    }
    Remove-Item $sttilepng, $sttilelog, $sttileerr -Force -ErrorAction SilentlyContinue
    Write-Host 'structure footprint smoke test: ok'
    # The floater's StructNameLbl is the map's own city name: `TCity.GetName`
    # hands back +0x48, which `TCity.ReadWrite` stores at rw tag 0xc as a
    # rwString (one length byte). Bloody Marauders' Human capital at (32,45)
    # stores "Venice ", so a real left click on its hex - screen (236,184) with
    # the opening camera, HXtoHP(32,45) = (1032,1440) minus cam (808,1268) plus
    # the 12 px map-window frame - must open the floater with that name instead
    # of the class label "City".
    $stclkpng = Join-Path $BinDir 'structure_click.png'
    $stclklog = Join-Path $BinDir 'structure_click.txt'
    $stclkerr = Join-Path $BinDir 'structure_click.err'
    Remove-Item $stclkpng, $stclklog, $stclkerr -Force -ErrorAction SilentlyContinue
    $stclkargs = ('--root "{0}" --start-map "Bloody Marauders.hsm" ' +
                  '--scen-human 0 --game-click 236 184 --render "{1}" ' +
                  '--no-music --no-cursor') -f $mroot, $stclkpng
    $stclkproc = Start-Process -FilePath (Join-Path $BinDir 'AoW.exe') `
        -ArgumentList $stclkargs -Wait -PassThru -NoNewWindow `
        -RedirectStandardOutput $stclklog -RedirectStandardError $stclkerr
    $stclkline = (Get-Content $stclklog -Raw) + (Get-Content $stclkerr -Raw)
    if ($stclkproc.ExitCode -ne 0) {
        throw "city name smoke test failed ($($stclkproc.ExitCode)): $stclkline"
    }
    if ($stclkline -notmatch [regex]::Escape('game_msg=selected structure (32,45)')) {
        throw "city name smoke test clicked the wrong hex: $stclkline"
    }
    if ($stclkline -notmatch [regex]::Escape('game_msg=selected structure (32,45) name=[Venice ]')) {
        throw "city name regression (TCity rw tag 0xc): $stclkline"
    }
    Remove-Item $stclkpng, $stclklog, $stclkerr -Force -ErrorAction SilentlyContinue
    Write-Host 'city name smoke test: ok'
    # The selected structure's blink is `bin/Screen Selection.gif`, not a smooth
    # sine: 13 map frames, opaque except the two consecutive frames 6-7 (offsets
    # 5-6 after the click) where the body drops to 50%. Barondir Bay's first city
    # is on screen at the opening camera; the 200x150 crop is only its tower, so
    # the map clock's water/flag animations cannot mask the result.
    $sfdir = Join-Path $BinDir 'struct_fade'
    New-Item -ItemType Directory -Force $sfdir | Out-Null
    $sfpng = @{}
    foreach ($n in @(4, 5, 6, 7)) {
        $p = Join-Path $sfdir "clock$n.png"
        Remove-Item $p -Force -ErrorAction SilentlyContinue
        $sfargs = ('--root "{0}" --start-map "Barondir Bay.HSM" --scen-human 0 ' +
                   '--structure-panel --game-clock {1} --crop 0 0 200 150 ' +
                   '--render "{2}" --no-music --no-cursor') -f $mroot, $n, $p
        $sfproc = Start-Process -FilePath (Join-Path $BinDir 'AoW.exe') `
            -ArgumentList $sfargs -Wait -PassThru -NoNewWindow
        if ($sfproc.ExitCode -ne 0) {
            throw "structure fade smoke test failed at clock $n ($($sfproc.ExitCode))"
        }
        if (-not (Test-Path $p)) {
            throw "structure fade smoke test produced no PNG at clock $n"
        }
        $sfpng[$n] = $p
    }
    $h4 = (Get-FileHash $sfpng[4]).Hash
    $h5 = (Get-FileHash $sfpng[5]).Hash
    $h6 = (Get-FileHash $sfpng[6]).Hash
    $h7 = (Get-FileHash $sfpng[7]).Hash
    if ($h4 -ne $h7) {
        throw 'structure fade regression: the two opaque frames (4 and 7) differ'
    }
    if ($h5 -ne $h6) {
        throw 'structure fade regression: the two dimmed frames (5 and 6) differ'
    }
    if ($h4 -eq $h5) {
        throw 'structure fade regression: frame 5 did not dim the building'
    }
    Remove-Item $sfdir -Recurse -Force
    Write-Host 'structure fade smoke test: ok'
    # The Scenario screen's per-race player choice must decide which race's cities
    # and armies (its units) are played - TSetupControl.SetupMap (0x557e0b64)
    # writes the screen's type back into the roster. Tutorial.hsm's default human
    # is the Halfling slot (index 1); marking the Goblin slot (race 10) Human must
    # move the played player to the Goblin player (index 2), so game_human becomes
    # 2 with race "Goblins" instead of staying on the Halflings.
    $shpng = Join-Path $BinDir 'game_scenhuman.png'
    $shlog = Join-Path $BinDir 'game_scenhuman.txt'
    Remove-Item $shpng, $shlog -Force -ErrorAction SilentlyContinue
    $shargs = '--root "{0}" --start-map "Tutorial.hsm" --scen-human 10 --render "{1}" --no-music --no-cursor' -f $mroot, $shpng
    $shproc = Start-Process -FilePath (Join-Path $BinDir 'AoW.exe') `
        -ArgumentList $shargs -Wait -PassThru -NoNewWindow `
        -RedirectStandardOutput $shlog
    if ($shproc.ExitCode -ne 0) {
        throw "scenario race-assignment smoke test failed ($($shproc.ExitCode))"
    }
    $shline = Get-Content $shlog -Raw
    if ($shline -notmatch 'game_human=2 race=Goblins') {
        throw "scenario race -> played units regression: $shline"
    }
    # The Events banner follows the seat: marking the Goblin race Human must also
    # move the banner's leader (the map's Goblin TLeader "Borok"), its plural
    # race name and its crest (ShieldsM 13 + 10 = 23).
    if ($shline -notmatch [regex]::Escape('name=Borok race=Goblins') -or
        $shline -notmatch [regex]::Escape('shield=23')) {
        throw "scenario race -> banner regression: $shline"
    }
    Remove-Item $shpng, $shlog -Force
    Write-Host 'scenario race-assignment smoke test: ok'

    Remove-Item $gmpng, $gmlog -Force
    Write-Host 'game smoke test: ok'

    # Audio decoder tests (Stage 3): decode every .IT song and a sample of the
    # .WAV/.VAG library, head-less (no sound device required).
    $atsrc = @(
        (Join-Path $Src 'engine\audio.cpp'),
        (Join-Path $Src 'engine\galaxy_it.cpp'),
        (Join-Path $Src 'engine\galaxy_player.cpp'),
        (Join-Path $Src 'engine\openmpt_player.cpp'),
        (Join-Path $Src 'tests\audio_test.cpp')
    )
    $atout = Join-Path $BinDir 'aow_audio_tests.exe'
    if ((Split-Path $cxx -Leaf) -like 'cl*') {
        & $cxx /nologo /std:c++17 /EHsc /W4 /I (Join-Path $Src 'include') `
            /Fe:$atout @atsrc /link winmm.lib openmpt.lib
    } else {
        & $cxx -std=c++17 -Wall -Wextra -Wpedantic -O2 `
            -I (Join-Path $Src 'include') @atsrc -o $atout -lwinmm -lopenmpt
    }
    if ($LASTEXITCODE -ne 0) { throw "audio test build failed ($LASTEXITCODE)" }
    & $atout (Join-Path $Here '..')
    if ($LASTEXITCODE -ne 0) { throw "audio tests failed ($LASTEXITCODE)" }

    # Playlist tests (Stage 3): the scenario's music playlist is walked in order
    # and wraps at the end (aow::scenario_playlist + aow::PlaylistPlayer).
    $psrc = @(
        (Join-Path $Src 'engine\pfs.cpp'),
        (Join-Path $Src 'engine\pfs_types.cpp'),
        (Join-Path $Src 'engine\inflate.cpp'),
        (Join-Path $Src 'engine\map.cpp'),
        (Join-Path $Src 'engine\map_resources.cpp'),
        (Join-Path $Src 'engine\unit_anim.cpp'),
        (Join-Path $Src 'engine\openmpt_player.cpp'),
        (Join-Path $Src 'engine\playlist.cpp'),
        (Join-Path $Src 'tests\playlist_test.cpp')
    )
    $pout = Join-Path $BinDir 'aow_playlist_tests.exe'
    if ((Split-Path $cxx -Leaf) -like 'cl*') {
        & $cxx /nologo /std:c++17 /EHsc /W4 /I (Join-Path $Src 'include') `
            /Fe:$pout @psrc /link openmpt.lib
    } else {
        & $cxx -std=c++17 -Wall -Wextra -Wpedantic -O2 `
            -I (Join-Path $Src 'include') @psrc -o $pout -lopenmpt
    }
    if ($LASTEXITCODE -ne 0) { throw "playlist test build failed ($LASTEXITCODE)" }
    & $pout (Join-Path $Here '..')
    if ($LASTEXITCODE -ne 0) { throw "playlist tests failed ($LASTEXITCODE)" }

    # galaxy loader test: verify the FUN_10020290 port against every song.
    $gsrc2 = @(
        (Join-Path $Src 'engine\galaxy_it.cpp'),
        (Join-Path $Src 'tests\galaxy_test.cpp')
    )
    $gout2 = Join-Path $BinDir 'aow_galaxy_tests.exe'
    if ((Split-Path $cxx -Leaf) -like 'cl*') {
        & $cxx /nologo /std:c++17 /EHsc /W4 /I (Join-Path $Src 'include') `
            /Fe:$gout2 @gsrc2
    } else {
        & $cxx -std=c++17 -Wall -Wextra -Wpedantic -O2 `
            -I (Join-Path $Src 'include') @gsrc2 -o $gout2
    }
    if ($LASTEXITCODE -ne 0) { throw "galaxy test build failed ($LASTEXITCODE)" }
    & $gout2 (Join-Path $Here '..')
    if ($LASTEXITCODE -ne 0) { throw "galaxy loader tests failed ($LASTEXITCODE)" }
}
