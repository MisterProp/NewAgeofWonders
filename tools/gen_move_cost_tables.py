"""gen_move_cost_tables.py - emit aow/move_cost_tables.hpp from the 8 move-cost
source tables the AoW1 engine keeps at AoWEPACK.dpl 0x558e84fc.

The engine builds its `MovePointTables` (256 tables x 256 bytes, BSS at
0x558ea040) at startup in `FUN_55744b2c` from eight 256-byte "source" tables
that live back-to-back at 0x558e84fc.  This script turns the Ghidra memory dump
of those 2048 bytes into a C++ header so the port uses the *original* numbers
rather than hand-authored ones.

The tables are indexed `[terrain*16 + overlay + 1]`: the field's `overlay` byte
is the *raw* TTerrainList code (-1 = none, 0 = mountains, 1 = forest, ...) and
column 0 of the table is "no overlay" - see `aow::move_point_cost` and
docs/15_MOVEMENT.md §2 ("The overlay code is one below the table column").

Dump the bytes (GhidraMCP bridge on 127.0.0.1:8089) first:

    python tools/ghidra/mcpq.py /AoWEPACK.dpl /read_memory \
        address=0x558e84fc length=2048 > tmp_tables.json

Then:

    python tools/gen_move_cost_tables.py tmp_tables.json \
        src/include/aow/move_cost_tables.hpp

The output is deterministic; the script is stdlib-only.
"""
import json
import os
import re
import sys

# The bit each source table is consumed under, in file order (FUN_55744b2c
# assigns local_4c..local_1c to 0x558e84fc + k*0x100 and tests the move-type
# byte's bits in this order: 0x01, 0x04, 0x02, 0x08, 0x10, 0x20, 0x40, 0x80).
BITS = [0x01, 0x04, 0x02, 0x08, 0x10, 0x20, 0x40, 0x80]
NAMES = ['walk', 'water', 'fly', 'forest', 'cave', 'mountain', 'bit6', 'bit7']

HEADER = '''\
// move_cost_tables.hpp - the eight move-cost source tables of the AoW1 engine.
// GENERATED by tools/gen_move_cost_tables.py - do not edit by hand.
//
// The engine fills `MovePointTables` (256 tables x 256 bytes, BSS at
// AoWEPACK.dpl 0x558ea040) at startup in `FUN_55744b2c` from eight 256-byte
// tables stored back-to-back at AoWEPACK.dpl **0x558e84fc**. For every
// `move_type` byte 0..255 and every cell `idx = terrain*16 + overlay + 1` it
// computes
//
//     v = 0x7F
//     for each bit b of move_type, in the order 0x01,0x04,0x02,0x08,0x10,0x20,
//     0x40,0x80:  if src[b][idx] != 0xFF and src[b][idx] < v:  v = src[b][idx]
//     MovePointTables[move_type][idx] = (v == 0x7F) ? 0xFF : v
//
// i.e. the cheapest of the selected movement modes, and 0xFF (impassable) when
// none applies.
//
// The index is `terrain*16 + overlay + 1`: `terrain` is the field's +0x14 (0
// water, 1 grass, 2 desert, 3 snow, 4 steppe, 5 wasteland, 6 ice, 7 earth,
// 8 rock, 9 lava, 10 dirt, 11 upper-wall, 12 upper-coast) and `overlay` its +0x15
// - the *raw* TTerrainList code (-1 = none/plains, 0 = mountains, 1 = forest,
// 2 = hill, 3 = scrub, 4 = road/city, 5 = bridge, 6 = rubble, 8 = bones,
// 9 = vegetation) - so column 0 is "no overlay" and a *mountain* is column 1.
// Both engine lookups add the 1: `TAbstractUnit.MovePointCost@0x55780848` reads
// its 256-byte buffer one byte after the table it filled in
// (`CreateMovePointTable` is handed `local_107`, the frame byte before
// `acStack_106`), and `TMoveControl.DefaultMoveOnMovePointProc@0x557454d8` reads
// `*(char *)(mc + field->terrain*0x10 + 0x31 + field->overlay)` with the table at
// `mc + 0x30`. See docs/15_MOVEMENT.md §2 ("The overlay code is one below the
// table column").
//
// The byte order of the eight tables is the file order at 0x558e84fc; the bit
// each is consumed under is `kMovePointSourceTableBits`.
#pragma once

#include <cstdint>

namespace aow {

// The move-type bit each source table is selected by, in table order.
inline constexpr std::uint8_t kMovePointSourceTableBits[8] = {
    0x01, 0x04, 0x02, 0x08, 0x10, 0x20, 0x40, 0x80};

// The eight tables, verbatim from AoWEPACK.dpl 0x558e84fc..0x558e8bfc.
// 0xFF = impassable; otherwise the move-point cost of that
// (terrain, overlay + 1) cell - column 0 is "no overlay".
inline constexpr std::uint8_t kMovePointSourceTables[8][256] = {
'''


def load(path):
    raw = open(path, 'rb').read()
    # mcpq.py writes through a PowerShell redirect, so the dump is UTF-16LE.
    if raw[:2] in (b'\xff\xfe', b'\xfe\xff'):
        text = raw.decode('utf-16')
    else:
        text = raw.decode('utf-8', 'replace')
    m = re.search(r'\{"address".*\}', text, re.S)
    if not m:
        raise SystemExit('no JSON memory dump in %s' % path)
    data = json.loads(m.group(0))['data']
    if len(data) != 2048:
        raise SystemExit('expected 2048 bytes, got %d' % len(data))
    return data


def main():
    src, dst = sys.argv[1], sys.argv[2]
    data = load(src)
    out = [HEADER]
    for k in range(8):
        tb = data[k * 256:(k + 1) * 256]
        out.append('    {  // table %d: bit 0x%02x (%s)\n' % (k, BITS[k], NAMES[k]))
        for r in range(0, 256, 16):
            row = ', '.join('0x%02x' % v for v in tb[r:r + 16])
            out.append('        %s,\n' % row)
        out.append('    },\n')
    out.append('};\n\n}  // namespace aow\n')
    text = ''.join(out)
    os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d bytes)' % (dst, len(text)))


if __name__ == '__main__':
    main()
