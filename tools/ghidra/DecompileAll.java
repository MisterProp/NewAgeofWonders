//DecompileAll.java - Ghidra headless script for the AoW1 port workflow.
//
//Runs after auto-analysis and, for every function, exports:
//   re/exports/<module>/<module>.decompiled.c   all functions, source-ordered
//   re/exports/<module>/<module>.functions.csv  address,name,size,signature
//   re/exports/<module>/<module>.strings.txt    string references
//
//Invoked via analyzeHeadless (see run_ghidra.ps1):
//   analyzeHeadless <projDir> <projName> -import AoW.exe \
//       -postScript DecompileAll.java -scriptPath tools/ghidra \
//       -deleteProject
//
//@category AoW

import java.io.File;
import java.io.PrintWriter;

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Data;
import ghidra.program.model.listing.DataIterator;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import ghidra.program.model.symbol.SourceType;

public class DecompileAll extends GhidraScript {

    @Override
    public void run() throws Exception {
        String outRoot = System.getenv("AOW_OUT");
        if (outRoot == null || outRoot.isEmpty()) {
            outRoot = new File(getScriptArgs().length > 0
                    ? getScriptArgs()[0] : ".").getAbsolutePath();
        }
        String module = currentProgram.getName().replaceAll("\\.[A-Za-z0-9]+$", "");
        File dir = new File(outRoot, module);
        dir.mkdirs();

        DecompInterface ifc = new DecompInterface();
        ifc.toggleCCode(true);
        ifc.toggleSyntaxTree(false);
        ifc.setSimplificationStyle("decompile");
        ifc.openProgram(currentProgram);

        File cFile = new File(dir, module + ".decompiled.c");
        File csvFile = new File(dir, module + ".functions.csv");
        int ok = 0, fail = 0;

        try (PrintWriter c = new PrintWriter(cFile, "UTF-8");
             PrintWriter csv = new PrintWriter(csvFile, "UTF-8")) {

            c.println("/* Auto-generated by DecompileAll.java (Ghidra) */");
            c.println("/* Module: " + module + " */");
            csv.println("address,name,size,isThunk,isExternal,signature");

            FunctionIterator fit = currentProgram.getFunctionManager()
                    .getFunctions(true);
            while (fit.hasNext() && !monitor.isCancelled()) {
                Function f = fit.next();
                long size = f.getBody().getNumAddresses();
                csv.printf("%s,%s,%d,%b,%b,\"%s\"%n",
                        f.getEntryPoint(), f.getName(), size,
                        f.isThunk(), f.isExternal(),
                        f.getPrototypeString(false, false).replace("\"", "'"));

                DecompileResults res = ifc.decompileFunction(f, 60, monitor);
                c.println("/* ==== " + f.getEntryPoint() + "  " + f.getName()
                        + " ==== */");
                if (res != null && res.decompileCompleted()) {
                    c.println(res.getDecompiledFunction().getC());
                    ok++;
                } else {
                    c.println("// decompile failed: "
                            + (res == null ? "null" : res.getErrorMessage()));
                    fail++;
                }
                c.println();
            }
        }

        File strFile = new File(dir, module + ".strings.txt");
        try (PrintWriter sw = new PrintWriter(strFile, "UTF-8")) {
            DataIterator dit = currentProgram.getListing().getDefinedData(true);
            while (dit.hasNext()) {
                Data data = dit.next();
                if (data.hasStringValue()) {
                    sw.printf("%s\t%s%n", data.getAddress(),
                            data.getValue());
                }
            }
        }

        println("DecompileAll: " + module + " ok=" + ok + " fail=" + fail
                + " -> " + dir.getAbsolutePath());
        ifc.dispose();

        // Remove the noisy DEFAULT source-type analysis name where possible so
        // later rename passes in re/symbols/import_renames.py can take over.
        renamePlaceholders();
    }

    private void renamePlaceholders() {
        FunctionIterator fit = currentProgram.getFunctionManager()
                .getFunctions(true);
        while (fit.hasNext()) {
            Function f = fit.next();
            if (f.getSymbol().getSource() == SourceType.DEFAULT) {
                // leave as-is; recorded here for the symbol-recovery stage
            }
        }
    }
}
